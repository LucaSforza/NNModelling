export function resolveLocale(value: string | null): Locale {
  return value === "it" ? "it" : "en";
}

const dynamicMessages = Object.entries(italianMessages).flatMap(([key, italian]) => {
  const parts = key.split(/(\{\w+\})/g);
  const names = parts
    .filter((part) => /^\{\w+\}$/.test(part))
    .map((part) => part.slice(1, -1));
  if (names.length === 0) return [];
  const source = parts.map((part) => /^\{\w+\}$/.test(part)
    ? "(.+?)"
    : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  return [{ key, italian, names, matcher: new RegExp(`^${source.join("")}$`) }];
});

export function translate(
  locale: Locale,
  key: string,
  values: Readonly<Record<string, string | number>> = {},
): string {
  let template = locale === "it" ? italianMessages[key] : undefined;
  let replacements = values;
  if (locale === "it" && !template) {
    for (const message of dynamicMessages) {
      const match = message.matcher.exec(key);
      if (!match) continue;
      template = message.italian;
      replacements = Object.fromEntries(message.names.map((name, index) => [name, match[index + 1]]));
      break;
    }
  }
  template ??= key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.hasOwn(replacements, name) ? String(replacements[name]) : placeholder,
  );
}
